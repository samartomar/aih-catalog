#!/usr/bin/env node
// Embeds the shipped tool profiles (`profiles/<id>.json`) in the `/contracts` entry point as
// their exact committed text, so the package carries them without a data-file export.
// `--check` compares instead of writing. Reads only files; runs nothing.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "src", "catalog", "internal", "profiles.generated.ts");
const ids = readdirSync(join(root, "profiles"))
  .filter((file) => file.endsWith(".json"))
  .map((file) => file.slice(0, -".json".length))
  .sort();
const key = (id) => (/^[A-Za-z_$][\w$]*$/.test(id) ? id : JSON.stringify(id));
const lines = [
  "// Generated by tools/generate-profiles.mjs from profiles/*.json; run `npm run generate:profiles`.",
  "",
  "/** The shipped tool profiles, by id, as the exact text of their committed documents. */",
  "export const profileTexts = {",
  ...ids.map((id) => `  ${key(id)}: ${JSON.stringify(readFileSync(join(root, "profiles", `${id}.json`), "utf8"))},`),
  "} as const;",
  "",
];
const text = lines.join("\n");
if (process.argv.includes("--check")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== text) {
    console.error("generate-profiles: src/catalog/internal/profiles.generated.ts is out of date; run npm run generate:profiles");
    process.exit(1);
  }
  console.log(`generate-profiles: ${ids.length} profiles match`);
} else {
  writeFileSync(target, text);
  console.log(`generate-profiles: wrote ${ids.length} profiles`);
}
