// Direct isolated process seam for emitted recipes; not a Core Apply or native-client claim.
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { cpSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { seedConsumerLock } from "./seed-consumer-lock.mjs";
const root = resolve(import.meta.dirname, "..");
const [node, npmCli, cache, output] = process.argv.slice(2);
assert.equal(process.argv.length, 6, "Usage: node tools/verify-ecc-mcp-acquisition.mjs <node26> <npm12-cli> <isolated-cache> <new-output>");
mkdirSync(output);
assert.equal(execFileSync(node, ["--version"], { encoding: "utf8", windowsHide: true }).trim(), "v26.12.1");
const hostNpm = resolve(process.execPath, "../node_modules/npm/bin/npm-cli.js");
const run = args => execFileSync(process.execPath, [hostNpm, ...args, "--cache", cache], { cwd: root, encoding: "utf8", windowsHide: true, timeout: 180000, maxBuffer: 1048576 });
const archive = join(output, JSON.parse(run(["pack", "--offline", "--ignore-scripts", "--json", "--pack-destination", output]))[0].filename);
const consumer = join(output, "consumer");
seedConsumerLock(consumer, root);
run(["install", "--prefix", consumer, "--offline", "--ignore-scripts", "--no-audit", "--no-fund", archive]);
cpSync(join(root, "tools/ecc-mcp-acquisition-scenario.mjs"), join(consumer, "scenario.mjs"));
writeFileSync(join(output, "invocation.json"), JSON.stringify({ seam: "direct emitted acquisition helper and isolated stdio", coreApply: "not-run", nativeClient: "not-run" }));
execFileSync(process.execPath, [join(consumer, "scenario.mjs"), node, npmCli, cache, output, archive], { cwd: consumer, windowsHide: true, stdio: "inherit", timeout: 1800000 });
console.log(JSON.stringify(JSON.parse(readFileSync(join(output, "receipt.json"))), null, 2));
